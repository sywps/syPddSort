'use strict';
// Generate the cloud copy from the exact client rules. --check never writes.
const fs = require('fs');
const path = require('path');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'cloudfunctions/pvpService/bot-runtime');
const check = process.argv.includes('--check');
function emit(relative, value) {
  const target = path.join(output, relative);
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== value) throw new Error(`stale bot runtime: ${relative}; run npm run pvp:bot:build`);
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, value);
  }
}
for (const name of ['LevelConfig', 'BoardModel', 'PchConveyorRules', 'PvpBotReplay', 'PchConveyorGeometry', 'PvpHumanReplay']) {
  const source = fs.readFileSync(path.join(root, `assets/Scripts/Core/${name}.ts`), 'utf8');
  const result = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 }, reportDiagnostics: true });
  if (result.diagnostics.length) throw new Error(`bot runtime compile failed: ${name}`);
  emit(`${name}.js`, '// Generated by scripts/build-pvp-bot-runtime.js; do not edit.\n' + result.outputText);
}
const files = fs.readdirSync(path.join(root, 'assets/LevelData')).filter(name => /^zt_level_\d+\.json$/.test(name)).sort();
for (const name of files) {
  const source = JSON.parse(fs.readFileSync(path.join(root, 'assets/LevelData', name), 'utf8'));
  const level = {};
  for (const key of ['boardWidth', 'boardHeight', 'timeLimit', 'conveyorCapacity', 'singleSelectionLimit', 'correctColorArr', 'initRandomColorArr']) {
    if (source[key] !== undefined) level[key] = source[key];
  }
  emit(`levels/${name}`, JSON.stringify(level) + '\n');
}
const catalog = files.map(name => {
  const level = JSON.parse(fs.readFileSync(path.join(root, 'assets/LevelData', name), 'utf8'));
  const cells = level.correctColorArr.flat().filter(color => color > 0);
  return { levelId: Number(name.match(/\d+/)[0]), cells: cells.length, colors: new Set(cells).size, timeLimit: level.timeLimit };
});
emit('levels/catalog.json', JSON.stringify(catalog) + '\n');
console.log(`PVP_BOT_RUNTIME_${check ? 'CHECKED' : 'GENERATED'}: 6 shared modules, ${files.length} pixel levels`);
