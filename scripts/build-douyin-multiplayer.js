'use strict';
// Generate standalone Douyin deployment files from the existing gameplay rules, not player data.
const fs = require('fs'), path = require('path'), ts = require('typescript');
const root = path.resolve(__dirname, '..'), output = path.join(root, 'cloudfunctions-douyin/multiplayer');
const check = process.argv.includes('--check');
const emitted = new Map();
function emit(name, text) {
    emitted.set(name, text);
    const target = path.join(output, name);
    if (check) { if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text) throw Error('stale Douyin multiplayer runtime: ' + name); }
    else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, text); }
}
function read(name) { return fs.readFileSync(path.join(root, name), 'utf8'); }
function replaceOne(source, from, to) {
    if (source.split(from).length !== 2) throw Error('shared service contract changed: ' + from);
    return source.replace(from, to);
}
let pvp = read('cloudfunctions/pvpService/index.js');
pvp = replaceOne(pvp, "const cloud = require('wx-server-sdk');", 'module.exports = function createPvpService(cloud) {\nconst exports = {};');
// Preserve source type for a truthful Douyin opponent label; public matchType remains ranked/friend.
pvp = replaceOne(pvp, 'opponentType: publicMatchType', "opponentType: match.matchType === 'bot' ? 'bot' : match.matchType === 'human_replay' ? 'human_replay' : publicMatchType");
emit('pvp/index.js', '// Generated by scripts/build-douyin-multiplayer.js; do not edit.\n' + pvp + '\nreturn exports;\n};\n');
for (const name of ['core', 'economy', 'matchmaking', 'replay-validation']) emit(`pvp/${name}.js`, read(`cloudfunctions/pvpService/${name}.js`));
emit('coop/core.js', read('cloudfunctions/coopService/core.js'));
for (const name of ['LevelConfig', 'BoardModel', 'PchConveyorRules', 'PvpBotReplay', 'PchConveyorGeometry', 'PvpHumanReplay', 'CoopModeConfig']) {
    const result = ts.transpileModule(read(`assets/Scripts/Core/${name}.ts`), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 }, reportDiagnostics: true });
    if (result.diagnostics.length) throw Error('multiplayer rule compile failed: ' + name);
    emit(`coop/runtime/${name}.js`, result.outputText);
    if (name !== 'CoopModeConfig') emit(`pvp/bot-runtime/${name}.js`, result.outputText);
}
const manifestText = read('assets/GameAssetsBundle/coop-manifest.json');
emit('coop/levels/manifest.json', manifestText);
for (const level of JSON.parse(manifestText).levels) emit('coop/levels/' + level.file, read('assets/LevelData/' + level.file));
// Legacy layout is still referenced by the shared core for previously created posts.
function copyTree(src, dest) {
    for (const item of fs.readdirSync(path.join(root, src), { withFileTypes: true })) {
        if (item.isDirectory()) copyTree(src + '/' + item.name, dest + '/' + item.name);
        else if (/\.(json|js)$/.test(item.name)) emit(dest + '/' + item.name, read(src + '/' + item.name));
    }
}
copyTree('cloudfunctions/coopService/legacy-levels', 'coop/legacy-levels');
const catalog = [];
for (const file of fs.readdirSync(path.join(root, 'assets/LevelData')).filter(name => /^zt_level_\d+\.json$/.test(name)).sort()) {
    const source = JSON.parse(read('assets/LevelData/' + file)), level = {};
    for (const key of ['boardWidth', 'boardHeight', 'timeLimit', 'conveyorCapacity', 'singleSelectionLimit', 'correctColorArr', 'initRandomColorArr']) if (source[key] !== undefined) level[key] = source[key];
    emit('pvp/bot-runtime/levels/' + file, JSON.stringify(level) + '\n');
    const cells = source.correctColorArr.flat().filter(color => color > 0);
    catalog.push({ levelId: Number(file.match(/\d+/)[0]), cells: cells.length, colors: new Set(cells).size, timeLimit: source.timeLimit });
}
emit('pvp/bot-runtime/levels/catalog.json', JSON.stringify(catalog) + '\n');
// One common code file for the cloud console; operators do not copy hundreds of level files.
const modules = [...emitted].map(([name, source]) => JSON.stringify(name) + ': function(module, exports, require) {\n'
    + (name.endsWith('.json') ? 'module.exports = ' + source.trim() + ';\n' : source) + '\n}').join(',\n');
const bundle = `'use strict';\n// Generated by scripts/build-douyin-multiplayer.js. Rules and level assets only.\nconst modules = {\n${modules}\n};\nconst cache = {};\nfunction load(id) {\n if (cache[id]) return cache[id].exports;\n if (!modules[id]) throw Error('Missing multiplayer module: ' + id);\n const module = { exports: {} }; cache[id] = module;\n modules[id](module, module.exports, name => {\n  if (name === 'crypto') return require('crypto');\n  if (!name.startsWith('.')) throw Error('Unexpected multiplayer dependency: ' + name);\n  const key = require('path').posix.normalize(require('path').posix.join(require('path').posix.dirname(id), name));\n  return load(modules[key] ? key : key + '.js');\n });\n return module.exports;\n}\nmodule.exports = { createCoopService: load('coop/core.js').createCoopService, createPvpService: load('pvp/index.js') };\n`;
const bundlePath = path.join(root, 'cloudfunctions-douyin/multiplayerRuntime.js');
if (check) { if (fs.readFileSync(bundlePath, 'utf8') !== bundle) throw Error('stale multiplayerRuntime bundle'); }
else fs.writeFileSync(bundlePath, bundle);
console.log(`Douyin multiplayer ${check ? 'checked' : 'generated'}: ${JSON.parse(manifestText).levels.length} coop levels, ${catalog.length} PVP levels; no player data copied.`);
