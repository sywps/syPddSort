'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const check = process.argv.includes('--check');
function emit(file, value) {
    if (check) {
        if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== value) throw new Error(`合作资源未同步: ${file}`);
        return;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const lines = value.match(/[^\n]*(?:\n|$)/g).filter(Boolean);
    fs.writeFileSync(file, lines.slice(0, 300).join(''));
    for (let i = 300; i < lines.length; i += 300) fs.appendFileSync(file, lines.slice(i, i + 300).join(''));
}
function meta(file, importer) {
    const target = file + '.meta';
    if (fs.existsSync(target)) return;
    if (check) throw new Error(`缺少资源 meta: ${target}`);
    emit(target, JSON.stringify({ ver: importer === 'typescript' ? '4.0.24' : '2.0.1', importer,
        imported: true, uuid: crypto.randomUUID(), files: importer === 'json' ? ['.json'] : [], subMetas: {}, userData: {} }, null, 2) + '\n');
}
for (const name of ['LevelConfig', 'BoardModel', 'PchConveyorRules', 'PvpBotReplay', 'PchConveyorGeometry', 'PvpHumanReplay', 'CoopModeConfig']) {
    const source = fs.readFileSync(path.join(root, `assets/Scripts/Core/${name}.ts`), 'utf8');
    const result = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 }, reportDiagnostics: true });
    if (result.diagnostics.length) throw new Error(`合作规则编译失败: ${name}`);
    emit(path.join(root, `cloudfunctions/coopService/runtime/${name}.js`), '// Generated by scripts/build-coop-runtime.js.\n' + result.outputText);
}
const sourceDir = path.join(root, 'assets/LevelData');
const manifestText = fs.readFileSync(path.join(root, 'assets/GameAssetsBundle/coop-manifest.json'), 'utf8');
const manifest = JSON.parse(manifestText);
emit(path.join(root, 'cloudfunctions/coopService/levels/manifest.json'), manifestText);
meta(path.join(root, 'assets/GameAssetsBundle/coop-manifest.json'), 'json');
for (const file of manifest.levels.map(level => level.file)) {
    const value = fs.readFileSync(path.join(sourceDir, file), 'utf8');
    emit(path.join(root, 'cloudfunctions/coopService/levels', file), value);
    meta(path.join(sourceDir, file), 'json');
}
for (const name of ['CoopModeConfig', 'CoopServiceMgr', 'GameCtrlModules/CoopModeModule', 'Panels/CoopPanelController']) {
    const file = path.join(root, `assets/Scripts/Core/${name}.ts`);
    if (fs.existsSync(file)) meta(file, 'typescript');
}
console.log(`COOP_RUNTIME_${check ? 'CHECKED' : 'GENERATED'}: 10 levels, 7 rule modules`);
