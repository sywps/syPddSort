'use strict';
// Extract pure rules from the existing, tested WeChat implementation. No SDK adapter is shipped.
const fs = require('fs'), path = require('path'), crypto = require('crypto'), ts = require('typescript');
const root = path.resolve(__dirname, '..');
const sources = {};
function declarations(file, excluded) {
    const source = fs.readFileSync(path.join(root, file), 'utf8');
    sources[file] = crypto.createHash('sha256').update(source).digest('hex');
    const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
    return ast.statements.filter(node => {
        if (ts.isFunctionDeclaration(node)) return !excluded.includes(node.name.text);
        if (ts.isVariableStatement(node)) return node.declarationList.declarations.every(d => !excluded.includes(d.name.text));
        return false;
    }).map(node => node.getText(ast)).join('\n\n');
}
const sync = declarations('cloudfunctions/syncUserState/index.js', ['cloud', 'db', 'findUserProfile', 'isCollectionMissing', 'isDuplicateProfileError']);
const chapter = declarations('cloudfunctions/updateUserProfileAssets/chapter-rewards.js', ['eligibleChapterRewards']);
const profile = declarations('cloudfunctions/updateUserProfileAssets/profile-customization.js', ['crypto', 'catalog', 'retired', 'execute', 'clone', '{ claimChapterRewards }']);
function read(file) {
    const value = fs.readFileSync(path.join(root, file), 'utf8');
    sources[file] = crypto.createHash('sha256').update(value).digest('hex');
    return value;
}
const policy = read('cloudfunctions/updateUserProfileAssets/chapter-reward-policy.js');
const catalog = JSON.stringify(JSON.parse(read('cloudfunctions/updateUserProfileAssets/profile-catalog.json')));
const retired = JSON.stringify(JSON.parse(read('cloudfunctions/updateUserProfileAssets/profile-retired.json')));
// Binding patterns have no .text; exclude require() declarations as well.
const pure = text => text.replace(/^const \{[^\n]+\} = require\([^\n]+\);\n?/gm, '');
const output = `'use strict';\n// GENERATED by scripts/build-douyin-business-rules.js. Do not hand-edit.\n` +
    `const sync = (() => {\n${sync}\nreturn { buildBaseProfile, buildProfilePatch, buildGameStatePatch, resolveEffectiveProgress, extractProfile, extractGameState, buildBackgroundSkinResetPersistPatch, buildBackgroundSkinRetirementPersistPatch };\n})();\n` +
    `const profile = (() => {\nconst catalog = ${catalog};\nconst retired = ${retired};\n` +
    `const { eligibleChapterRewards } = (() => { const exports = {};\n${policy}\nreturn exports; })();\n` +
    `${pure(chapter)}\n${pure(profile)}\nreturn { transition, normalize, inventory };\n})();\n` +
    `module.exports = { sync, profile, sources: ${JSON.stringify(sources, null, 2)} };\n`;
if (/require\(/.test(output)) throw Error('Pure rules must not depend on runtime modules');
const target = path.join(root, 'cloudfunctions-douyin/businessRules.js');
if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw Error('Douyin business rules are stale; regenerate');
} else fs.writeFileSync(target, output);
console.log('Douyin pure business rules verified');
