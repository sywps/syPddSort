export function installGameplaySlotSkillModule(target: any): void {
    Object.assign(target, {
        buildSlotArea(root: Node) {
            ensureGameplaySlotUiController(this).buildSlotArea(root);
        },

        getSlotAreaCenterY(): number {
            return ensureGameplaySlotUiController(this).getSlotAreaCenterY();
        },

        /** 重建暂存槽节点（初始化或解锁后调用） */
        rebuildSlotNodes() {
            ensureGameplaySlotUiController(this).rebuildSlotNodes();
        },

        /** 旧扩容入口统一收敛为解锁暂存槽 */
        onAddSlotRow() {
            ensureGameplaySlotUiController(this).onAddSlotRow();
        },

        unlockSlotRow() {
            ensureGameplaySlotUiController(this).unlockSlotRow();
        },

        /** 点击解锁按钮：免费模式直接解锁，广告模式看广告解锁 */
        tryUnlockSlotRow() {
            ensureGameplaySlotUiController(this).tryUnlockSlotRow();
        },

        /** 判断暂存槽是否有豆豆 */
        slotHasBeans(): boolean {
            return ensureGameplaySlotUiController(this).slotHasBeans();
        },

        showExpandSlotGuide() {
            ensureGameplaySlotUiController(this).showExpandSlotGuide();
        },

        clearExpandSlotGuide() {
            ensureGameplaySlotUiController(this).clearExpandSlotGuide();
        },

        buildSkillButtons(root: Node) {
            ensureGameplaySkillUiController(this).buildSkillButtons(root);
        },

        rebuildSkillButtonsUI() {
            ensureGameplaySkillUiController(this).rebuildSkillButtonsUI();
        },

        updateCountBadge(parent: Node, count: number, showWhenZero: boolean = false) {
            ensureGameplaySkillUiController(this).updateCountBadge(parent, count, showWhenZero);
        },

    });
}
